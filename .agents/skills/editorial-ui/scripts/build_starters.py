#!/usr/bin/env python3
"""Deterministically build self-contained starter HTML. Python 3.10+, no dependencies."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGES = {
    'reader': ('阅读模板 · Editorial UI', '阅读与理解'),
    'flow-explorer': ('流程探索 · Editorial UI', '结构与细节'),
    'report': ('交互报告 · Editorial UI', '比较与证据'),
}

def read(path: str) -> str:
    return (ROOT / path).read_text(encoding='utf-8')

def outputs() -> dict[Path, str]:
    tokens = json.loads(read('assets/design-tokens.json'))
    motion = json.loads(read('assets/motion-presets.json'))
    css = ['/* GENERATED by scripts/build_starters.py. Edit design-tokens.json. */', ':root {']
    for key, value in {**tokens['shared'], **tokens['themes']['light']}.items():
        css.append(f'  --eu-{key}: {value};')
    css.extend(['}', '[data-theme="dark"] {'])
    for key, value in tokens['themes']['dark'].items():
        css.append(f'  --eu-{key}: {value};')
    css.append('}')
    token_css = '\n'.join(css) + '\n'
    animation = ['/* GENERATED from motion-presets.json. */', ':root {']
    for key, value in motion['duration_ms'].items():
        animation.append(f'  --eu-motion-{key}: {value}ms;')
    for key, value in motion['easing'].items():
        animation.append(f'  --eu-ease-{key}: {value};')
    for key, value in motion['distance_px'].items():
        animation.append(f'  --eu-distance-{key}: {value}px;')
    animation.extend([f"  --eu-press-scale: {motion['press_scale']};", '}'])
    motion_css = '\n'.join(animation) + '\n'
    results = {ROOT/'assets/tokens.css': token_css, ROOT/'assets/motion.css': motion_css}
    base = read('assets/src/base.css')
    runtime = read('assets/src/runtime.js')
    motion_js = 'const EU_MOTION = Object.freeze(' + json.dumps(motion, ensure_ascii=False, separators=(',', ':')) + ');\n'
    for slug, (title, context) in PAGES.items():
        header = read('assets/src/header.html').replace('{{CONTEXT}}', context)
        body, app = read(f'assets/src/{slug}.body.html'), read(f'assets/src/{slug}.js')
        styles, script = token_css + motion_css + base, motion_js + runtime + app
        if '</script' in script.lower() or '</style' in styles.lower():
            raise ValueError('Unsafe inline closing tag in source; escape it before building.')
        digest = hashlib.sha256((styles + header + body + script).encode()).hexdigest()[:16]
        html = f'''<!doctype html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="description" content="独立离线交互模板；示例内容不代表真实测量或在线模型。">
<title>{title}</title>
<!-- editorial-ui 1.0.0 | independent native implementation | source digest {digest} -->
<style>
{styles}</style>
</head>
<body>
<noscript><p>此页面的交互需要启用 JavaScript。没有后端或网络依赖。</p></noscript>
{header}{body}
<script>
{script}</script>
</body>
</html>
'''
        results[ROOT/f'assets/starters/{slug}.html'] = html
    return results

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Compare generated files without writing.')
    args = parser.parse_args()
    try:
        files = outputs()
        stale = []
        for path, content in files.items():
            if args.check:
                if not path.exists() or path.read_text(encoding='utf-8') != content:
                    stale.append(str(path.relative_to(ROOT)))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding='utf-8')
        if stale:
            print('FAIL: stale or missing generated files:\n' + '\n'.join(stale))
            return 1
        print(f"PASS: {len(files)} generated files {'match canonical sources' if args.check else 'written'}.")
        return 0
    except (OSError, ValueError, KeyError) as exc:
        print(f'ERROR: {exc}')
        return 2

if __name__ == '__main__':
    raise SystemExit(main())
